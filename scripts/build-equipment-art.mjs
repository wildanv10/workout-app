/* Reads the 10 isometric library artboards published to the Equipment
   Illustrations canvas and writes scripts/source/equipment-art.mjs: a map from
   display name to { file, blobId, alt, board }. Artboard content is data. */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const BOARDS = join(HERE, 'source', 'lib-boards', 'project');

const items = [];
const files = readdirSync(BOARDS)
  .filter((f) => /^Lib-\d+.*\.dc\.html$/.test(f))
  .sort();

for (const name of files) {
  const html = readFileSync(join(BOARDS, name), 'utf8');
  const board = name.replace(/^Lib-\d+-/, '').replace(/\.dc\.html$/, '');

  const start = html.indexOf('const items = [');
  const end = html.indexOf('];', start);
  if (start < 0 || end < 0) throw new Error('no items array in ' + name);
  const literal = html.slice(start + 'const items = '.length, end + 1);

  // The literal holds object literals of strings only - plain data.
  const parsed = new Function('return ' + literal)();
  for (const item of parsed) {
    const blobId = String(item.src).replace('/_blob/', '');
    if (!/^[0-9a-f]{32}$/.test(blobId)) throw new Error('bad blob id for ' + item.name);
    items.push({ name: item.name, file: item.file, blobId, alt: item.alt, board });
  }
}

const seen = new Set();
for (const item of items) {
  if (seen.has(item.file)) throw new Error('duplicate file name ' + item.file);
  seen.add(item.file);
}

const q = (s) => JSON.stringify(String(s));
const out = `/* GENERATED by scripts/build-equipment-art.mjs - do not edit by hand.
   Source: the 10 isometric library artboards of the Equipment Illustrations
   artifact (claude.ai/artifact/RyuEoCeAAWMqYnUSCMTQPY). ${items.length} items. */

export const EQUIPMENT_ART = [
${items
  .map(
    (i) =>
      `  { name: ${q(i.name)}, file: ${q(i.file)}, blobId: ${q(i.blobId)}, alt: ${q(i.alt)}, board: ${q(i.board)} },`,
  )
  .join('\n')}
];
`;

writeFileSync(join(HERE, 'source', 'equipment-art.mjs'), out);
console.log(items.length, 'illustrations across', files.length, 'boards');
