/* Generates data/muscles.ts, data/equipment.ts and data/exercises.ts from the
   verbatim artifact data in scripts/source/, joined with the English step
   translations in scripts/steps/.

   Run: npm run extract-data
   The generated files are committed; this script exists so they can be
   regenerated if the source data changes. */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { GROUPS, MUSCLES, MACRO, EQUIP, SECTIONS } from './source/exercise-library.data.mjs';
import { MUSCLE_GROUPS } from './source/muscle-groups.data.mjs';
import { EQUIPMENT_ART } from './source/equipment-art.mjs';
import STEPS_EN from './steps/index.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BANNER = `/* GENERATED by scripts/extract-data.mjs - do not edit by hand.
   Source: the Exercise Library and Atlas Ecorche artifacts (see scripts/source/). */\n`;

// ---------------------------------------------------------------- config

/** Indonesian section name -> English id + label. Order is the dataset's order. */
const SECTION_MAP = {
  Dada: ['chest', 'Chest'],
  Punggung: ['back', 'Back'],
  Bahu: ['shoulders', 'Shoulders'],
  Lengan: ['arms', 'Arms'],
  'Kaki & Bokong': ['legs', 'Legs & Glutes'],
  Core: ['core', 'Core'],
  'Full body & Kardio': ['fullbody', 'Full Body & Cardio'],
};

/** English descriptions of what each muscle group does (Ecorche descriptions). */
const GROUP_DESC = {
  chest: 'Pushes your arms forward and draws them toward the middle of your body.',
  shoulders: 'Raises your arms to the front, side, and back.',
  traps: 'Lifts, pulls, and stabilises your shoulder blades.',
  biceps: 'Bends your elbow and turns your palm upward.',
  triceps: 'Straightens your elbow; the long head also helps pull your arm backward.',
  forearms: 'Grips, and bends and straightens your wrist.',
  lats: 'Pulls your arms down and back, and gives your back its width.',
  midback: 'Draws your shoulder blades together and rotates your arms outward.',
  abs: 'Flexes your torso and holds abdominal pressure.',
  obliques: 'Rotates and side-bends your torso; includes the serratus anterior.',
  lowback: 'Extends your spine and holds your posture.',
  glutes: 'Extends and opens your hips; includes the gluteus medius and TFL.',
  quads: 'Straightens your knee; the rectus femoris also flexes your hip.',
  adductors: 'Draws your thighs toward the midline of your body.',
  hamstrings: 'Bends your knee and extends your hip.',
  calves: 'Raises your heels; the tibialis and peroneus control your ankle.',
};

const REGION_LABEL = { upper: 'Upper body', core: 'Core', lower: 'Lower body' };

/** Equipment category id -> label + the codes it holds. Mirrors the 10 boards
    of the Equipment Illustrations canvas, collapsed to the 41 codes in use. */
const EQUIPMENT_CATEGORIES = [
  ['freeWeights', 'Free weights', ['bb', 'pl', 'bump', 'db', 'kb', 'ez', 'hex', 'mb']],
  ['benchesRacks', 'Benches, racks & stations',
    ['fb', 'ab', 'dec', 'prb', 'rack', 'smith', 'pub', 'dip', 'be', 'ghd', 'lm']],
  ['cables', 'Cable machines', ['cc', 'lpd', 'scr', 'catt']],
  ['machinesUpper', 'Machines: upper body', ['cpm', 'pd', 'spm', 'tbar']],
  ['machinesLower', 'Machines: lower body', ['lp', 'hs', 'le', 'lc', 'hab', 'crm']],
  ['smallGear', 'Small & bodyweight gear', ['rings', 'par', 'awh', 'mat', 'band', 'box']],
  ['cardio', 'Cardio', ['jr', 'ropes']],
];

/** Exercise name -> fig-poses animation template, only where the motion really
    matches. Everything else falls back to an equipment illustration. */
const ANIM = {
  squat: ['Barbell Back Squat', 'Front Squat', 'Bodyweight Squat', 'Hack Squat', 'Leg Press',
    'Bulgarian Split Squat', 'Pistol Squat'],
  gobletsquat: ['Goblet Squat'],
  deadlift: ['Barbell Deadlift', 'Trap Bar Deadlift', 'Romanian Deadlift', 'Sumo Deadlift'],
  row: ['Bent-over Barbell Row', 'One-arm Dumbbell Row', 'Seated Cable Row', 'T-Bar Row'],
  curl: ['Barbell Curl', 'Alternating Dumbbell Curl', 'Hammer Curl', 'Preacher Curl',
    'Incline Dumbbell Curl', 'Reverse Curl'],
  press: ['Barbell Overhead Press', 'Seated Dumbbell Shoulder Press', 'Arnold Press',
    'Machine Shoulder Press'],
  lateral: ['Dumbbell Lateral Raise'],
  triext: ['Overhead Triceps Extension', 'Triceps Pushdown'],
  pushup: ['Push-up', 'Diamond Push-up', 'Archer Push-up', 'Pseudo Planche Push-up'],
  plank: ['Plank'],
  bench: ['Barbell Bench Press', 'Incline Barbell Bench Press', 'Decline Bench Press',
    'Dumbbell Bench Press', 'Incline Dumbbell Press', 'Close-grip Bench Press',
    'Machine Chest Press'],
  crunch: ['Crunch'],
  bridge: ['Glute Bridge', 'Barbell Hip Thrust'],
  calf: ['Standing Calf Raise'],
};
const ANIM_OF = {};
for (const [key, names] of Object.entries(ANIM)) for (const n of names) ANIM_OF[n] = key;

const CATEGORY_OF = { G: 'gym', B: 'bodyweight', C: 'calisthenics' };
const LEVEL_LABEL = { 1: 'Beginner', 2: 'Intermediate', 3: 'Advanced' };

// ---------------------------------------------------------------- helpers

const problems = [];
const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const slug = (s) => s.toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** Expand MACRO shorthand exactly as the library's own `ex()` helper does. */
const expandMuscles = (s) =>
  (s || '').split(/\s+/).filter(Boolean).flatMap((t) => (MACRO[t] ? MACRO[t].split(' ') : [t]));

// ---------------------------------------------------------------- muscles

const groupOrder = MUSCLE_GROUPS.map((g) => g.id);
const groupById = Object.fromEntries(MUSCLE_GROUPS.map((g) => [g.id, g]));

for (const id of Object.keys(GROUPS)) {
  if (!groupById[id]) problems.push(`muscle group '${id}' is in the Exercise Library but not in Ecorche`);
}

const musclesTs = `${BANNER}
export type MuscleGroupId =
${groupOrder.map((id) => `  | '${id}'`).join('\n')};

export type BodyRegion = 'upper' | 'core' | 'lower';

export interface MuscleGroup {
  id: MuscleGroupId;
  /** Display name, e.g. "Lower back". */
  name: string;
  region: BodyRegion;
  /** Hex colour shared with the Ecorche anatomy model. */
  color: string;
  /** What the group does, in one sentence. */
  description: string;
}

export interface Muscle {
  id: string;
  /** Anatomical name, e.g. "Biceps brachii (long head)". */
  name: string;
  group: MuscleGroupId;
}

export const REGION_LABELS: Record<BodyRegion, string> = {
${Object.entries(REGION_LABEL).map(([k, v]) => `  ${k}: ${q(v)},`).join('\n')}
};

export const MUSCLE_GROUPS: MuscleGroup[] = [
${MUSCLE_GROUPS.map((g) => `  { id: '${g.id}', name: ${q(g.name)}, region: '${g.region}', color: '${g.color}', description: ${q(GROUP_DESC[g.id] ?? '')} },`).join('\n')}
];

export const MUSCLES: Muscle[] = [
${Object.entries(MUSCLES).map(([id, [name, group]]) => `  { id: '${id}', name: ${q(name)}, group: '${group}' },`).join('\n')}
];

const groupIndex = new Map(MUSCLE_GROUPS.map((g) => [g.id, g]));
const muscleIndex = new Map(MUSCLES.map((m) => [m.id, m]));

export const getMuscleGroup = (id: MuscleGroupId): MuscleGroup | undefined => groupIndex.get(id);
export const getMuscle = (id: string): Muscle | undefined => muscleIndex.get(id);

/** Group ids for a list of individual muscle ids, de-duplicated, in group order. */
export function groupsOf(muscleIds: readonly string[]): MuscleGroupId[] {
  const seen = new Set<MuscleGroupId>();
  for (const id of muscleIds) {
    const m = muscleIndex.get(id);
    if (m) seen.add(m.group);
  }
  return MUSCLE_GROUPS.filter((g) => seen.has(g.id)).map((g) => g.id);
}
`;

// -------------------------------------------------------------- equipment

// Illustrations join to equipment by exact display name - all 41 match.
const artByName = new Map(EQUIPMENT_ART.map((a) => [a.name, a]));
for (const name of Object.values(EQUIP)) {
  if (!artByName.has(name)) problems.push(`no illustration for equipment '${name}'`);
}

const categoryOfCode = {};
for (const [id, , codes] of EQUIPMENT_CATEGORIES) for (const c of codes) categoryOfCode[c] = id;
for (const code of Object.keys(EQUIP)) {
  if (!categoryOfCode[code]) problems.push(`equipment code '${code}' (${EQUIP[code]}) has no category`);
}
for (const code of Object.keys(categoryOfCode)) {
  if (!EQUIP[code]) problems.push(`category references unknown equipment code '${code}'`);
}

const equipmentTs = `${BANNER}
export type EquipmentCode =
${Object.keys(EQUIP).map((c) => `  | '${c}'`).join('\n')};

export type EquipmentCategoryId =
${EQUIPMENT_CATEGORIES.map(([id]) => `  | '${id}'`).join('\n')};

export interface Equipment {
  code: EquipmentCode;
  /** Display name, matching the Equipment Illustrations library. */
  name: string;
  category: EquipmentCategoryId;
  /** File under /equipment/, set once the isometric art is pulled in. */
  svg?: string;
  /** Alt text for the illustration. */
  alt?: string;
}

export interface EquipmentCategory {
  id: EquipmentCategoryId;
  name: string;
  codes: EquipmentCode[];
}

export const EQUIPMENT: Equipment[] = [
${Object.entries(EQUIP)
  .map(([code, name]) => {
    const art = artByName.get(name);
    const extra = art ? `, svg: ${q(art.file)}, alt: ${q(art.alt)}` : '';
    return `  { code: '${code}', name: ${q(name)}, category: '${categoryOfCode[code]}'${extra} },`;
  })
  .join('\n')}
];

export const EQUIPMENT_CATEGORIES: EquipmentCategory[] = [
${EQUIPMENT_CATEGORIES.map(([id, name, codes]) => `  { id: '${id}', name: ${q(name)}, codes: [${codes.map((c) => `'${c}'`).join(', ')}] },`).join('\n')}
];

const equipmentIndex = new Map(EQUIPMENT.map((e) => [e.code, e]));

export const getEquipment = (code: EquipmentCode): Equipment | undefined => equipmentIndex.get(code);
export const equipmentName = (code: EquipmentCode): string => equipmentIndex.get(code)?.name ?? code;

/** Every equipment code, for the "full gym" setup. */
export const ALL_EQUIPMENT_CODES: EquipmentCode[] = EQUIPMENT.map((e) => e.code);
`;

// -------------------------------------------------------------- exercises

const exercises = [];
const usedIds = new Set();

for (const [sectionNameId, list] of SECTIONS) {
  const mapped = SECTION_MAP[sectionNameId];
  if (!mapped) {
    problems.push(`section '${sectionNameId}' has no English mapping`);
    continue;
  }
  const [sectionId] = mapped;
  for (const x of list) {
    const id = slug(x.n);
    if (usedIds.has(id)) problems.push(`duplicate exercise id '${id}' from '${x.n}'`);
    usedIds.add(id);

    const steps = STEPS_EN[x.n];
    if (!steps) {
      problems.push(`no English steps for '${x.n}'`);
    } else if (steps.length !== x.st.length) {
      problems.push(`'${x.n}': ${steps.length} English steps but ${x.st.length} in the source`);
    }

    const equipment = (x.e || '').split(/\s+/).filter(Boolean).map((token) => {
      const optional = token.endsWith('?');
      const code = optional ? token.slice(0, -1) : token;
      if (!EQUIP[code]) problems.push(`'${x.n}' references unknown equipment code '${code}'`);
      return { code, optional };
    });

    const primary = expandMuscles(x.p);
    const secondary = expandMuscles(x.s);
    for (const m of [...primary, ...secondary]) {
      if (!MUSCLES[m]) problems.push(`'${x.n}' references unknown muscle '${m}'`);
    }
    if (!primary.length) problems.push(`'${x.n}' has no primary muscles`);

    const groupSet = new Set([...primary, ...secondary].map((m) => MUSCLES[m]?.[1]).filter(Boolean));

    exercises.push({
      id,
      name: x.n,
      section: sectionId,
      categories: x.c.split('').map((c) => CATEGORY_OF[c]),
      level: x.l,
      equipment,
      primary,
      secondary,
      groups: groupOrder.filter((g) => groupSet.has(g)),
      steps: steps ?? [],
      anim: ANIM_OF[x.n],
    });
  }
}

const exerciseTs = (e) => {
  const eq = e.equipment.map((q2) => `{ code: '${q2.code}'${q2.optional ? ', optional: true' : ''} }`).join(', ');
  return `  {
    id: '${e.id}',
    name: ${q(e.name)},
    section: '${e.section}',
    categories: [${e.categories.map((c) => `'${c}'`).join(', ')}],
    level: ${e.level},
    equipment: [${eq}],
    primary: [${e.primary.map((m) => `'${m}'`).join(', ')}],
    secondary: [${e.secondary.map((m) => `'${m}'`).join(', ')}],
    groups: [${e.groups.map((g) => `'${g}'`).join(', ')}],${e.anim ? `\n    anim: '${e.anim}',` : ''}
    steps: [
${e.steps.map((s) => `      ${q(s)},`).join('\n')}
    ],
  },`;
};

const exercisesTs = `${BANNER}
import type { MuscleGroupId } from './muscles';
import type { EquipmentCode } from './equipment';

export type SectionId =
${Object.values(SECTION_MAP).map(([id]) => `  | '${id}'`).join('\n')};

export type ExerciseCategory = 'gym' | 'bodyweight' | 'calisthenics';

/** 1 beginner, 2 intermediate, 3 advanced. */
export type Level = 1 | 2 | 3;

/** Animation templates available in engine/fig-poses.js. */
export type AnimKey =
${Object.keys(ANIM).map((k) => `  | '${k}'`).join('\n')};

export interface ExerciseEquipment {
  code: EquipmentCode;
  /** Optional gear can be substituted or skipped - it never gates availability. */
  optional?: boolean;
}

export interface Exercise {
  id: string;
  name: string;
  section: SectionId;
  categories: ExerciseCategory[];
  level: Level;
  equipment: ExerciseEquipment[];
  /** Individual muscle ids, MACRO shorthand already expanded. */
  primary: string[];
  secondary: string[];
  /** Muscle groups touched by primary or secondary muscles, derived. */
  groups: MuscleGroupId[];
  anim?: AnimKey;
  steps: string[];
}

export interface Section {
  id: SectionId;
  name: string;
}

export const SECTIONS: Section[] = [
${Object.values(SECTION_MAP).map(([id, name]) => `  { id: '${id}', name: ${q(name)} },`).join('\n')}
];

export const LEVEL_LABELS: Record<Level, string> = {
${Object.entries(LEVEL_LABEL).map(([k, v]) => `  ${k}: ${q(v)},`).join('\n')}
};

export const CATEGORY_LABELS: Record<ExerciseCategory, string> = {
  gym: 'Gym',
  bodyweight: 'Bodyweight',
  calisthenics: 'Calisthenics',
};

export const EXERCISES: Exercise[] = [
${exercises.map(exerciseTs).join('\n')}
];

const exerciseIndex = new Map(EXERCISES.map((e) => [e.id, e]));

export const getExercise = (id: string): Exercise | undefined => exerciseIndex.get(id);
`;

// ----------------------------------------------------------------- output

if (problems.length) {
  console.error(`\n${problems.length} problem(s) found - nothing written:\n`);
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}

writeFileSync(join(ROOT, 'data', 'muscles.ts'), musclesTs);
writeFileSync(join(ROOT, 'data', 'equipment.ts'), equipmentTs);
writeFileSync(join(ROOT, 'data', 'exercises.ts'), exercisesTs);

const animCount = exercises.filter((e) => e.anim).length;
console.log('data/muscles.ts    ', MUSCLE_GROUPS.length, 'groups,', Object.keys(MUSCLES).length, 'muscles');
console.log('data/equipment.ts  ', Object.keys(EQUIP).length, 'items,', EQUIPMENT_CATEGORIES.length, 'categories');
console.log('data/exercises.ts  ', exercises.length, 'exercises,', animCount, 'with animations');
